// Language state
let currentLanguage = 'en';

// Initialize language from localStorage or browser preference
function initLanguage() {
  const saved = localStorage.getItem('sim-language');
  if (saved && I18N_COMMON[saved]) {
    currentLanguage = saved;
  } else {
    const browserLang = navigator.language.split('-')[0];
    if (I18N_COMMON[browserLang]) {
      currentLanguage = browserLang;
    }
  }
  return currentLanguage;
}

// Get translation for a key (with fallback to English)
function t(key, lang = currentLanguage) {
  const dict = I18N_COMMON[lang] || I18N_COMMON.en;
  return dict[key] || I18N_COMMON.en[key] || key;
}

// Set current language and update all elements with data-i18n
function setLanguage(lang, pageTranslations = {}) {
  if (!I18N_COMMON[lang]) return false;

  currentLanguage = lang;
  localStorage.setItem('sim-language', lang);
  document.documentElement.lang = lang;

  // Update all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    let translation = t(key, lang);

    // Check page-specific translations first
    if (pageTranslations[lang] && pageTranslations[lang][key]) {
      translation = pageTranslations[lang][key];
    }

    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.type === 'search' || el.type === 'text') {
        el.placeholder = translation;
      } else {
        el.value = translation;
      }
    } else if (el.tagName === 'OPTION') {
      el.textContent = translation;
    } else {
      el.textContent = translation;
    }
  });

  // Update document title if it has data-i18n
  const titleEl = document.querySelector('title[data-i18n]');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n');
    let translation = t(key, lang);
    if (pageTranslations[lang] && pageTranslations[lang][key]) {
      translation = pageTranslations[lang][key];
    }
    document.title = translation;
  }

  // Update language selector dropdowns
  document.querySelectorAll('#langSelect, .lang-selector select').forEach(select => {
    select.value = lang;
  });

  return true;
}

// Create language selector HTML
function createLanguageSelector() {
  return `
    <div class="lang-selector">
      <select id="langSelect" aria-label="${t('language')}">
        <option value="en">English</option>
        <option value="es">Español</option>
        <option value="it">Italiano</option>
        <option value="fr">Français</option>
        <option value="de">Deutsch</option>
      </select>
    </div>
  `;
}

// Initialize language selector event listeners
function initLanguageSelector(pageTranslations = {}) {
  document.querySelectorAll('#langSelect, .lang-selector select').forEach(select => {
    select.addEventListener('change', (e) => {
      setLanguage(e.target.value, pageTranslations);
      // Trigger page-specific redraw if needed
      if (typeof window.onLanguageChange === 'function') {
        window.onLanguageChange(e.target.value);
      }
    });
  });
}

